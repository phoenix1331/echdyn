import { format, resolveConfig } from "prettier";
import { describe, expect, it } from "vitest";
import { renderReport } from "./report";
import type { ModelSummary } from "./score";

const summary = (model: string, accuracy: number): ModelSummary => ({
  model,
  documents: 30,
  fieldAccuracy: accuracy,
  documentAccuracy: 0.5,
  accuracyByField: { supplier: 1, vat_gbp: accuracy },
  flaggedShare: 0.4,
  autoApproved: 18,
  approvedWithErrors: 1,
  failed: 0,
  medianDurationMs: 64_300,
  byLayout: {
    "Severn Valley Energy": {
      documents: 10,
      fieldAccuracy: accuracy - 0.1,
      documentAccuracy: 0.2,
      flaggedShare: 0.8,
    },
  },
  bySet: {
    synthetic: {
      documents: 30,
      fieldAccuracy: accuracy,
      documentAccuracy: 0.5,
      flaggedShare: 0.4,
      readBy: [model],
      medianDurationMs: 40_000,
    },
    scanned: {
      documents: 5,
      fieldAccuracy: 0.8,
      documentAccuracy: 0.2,
      flaggedShare: 1,
      readBy: [],
      medianDurationMs: 300_000,
    },
  },
});

describe("renderReport", () => {
  const report = renderReport([summary("llama3.2", 0.9167), summary("qwen3:8b", 0.98)], {
    date: "2026-10-29",
    promptVersion: "text-v1",
    sets: [{ name: "synthetic", documents: 30 }],
  });
  // Table cells are padded, so compare content with runs of spaces collapsed
  const compact = report.replace(/ {2,}/g, " ").replace(/-{3,}/g, "---");

  it("states what was measured and how", () => {
    expect(report).toContain(
      "Generated by `pnpm eval` on 2026-10-29. Prompt `text-v1`. Sets: synthetic (30 documents).",
    );
  });

  it("has one summary row per model", () => {
    expect(compact).toContain("| llama3.2 | 91.7% | 50.0% | 40.0% | 1 of 18 | 0 | 64.3 s |");
    expect(compact).toContain("| qwen3:8b | 98.0% |");
  });

  it("has a per-field table with a column per model", () => {
    expect(compact).toContain("| Field | llama3.2 | qwen3:8b |");
    expect(compact).toContain("| `vat_gbp` | 91.7% | 98.0% |");
  });

  it("breaks accuracy down by layout for each model", () => {
    expect(compact).toContain(
      "| Layout | Model | Documents | Field accuracy | Documents fully correct | Flagged |",
    );
    expect(compact).toContain("| Severn Valley Energy | llama3.2 | 10 | 81.7% | 20.0% | 80.0% |");
    expect(compact).toContain("| Severn Valley Energy | qwen3:8b | 10 | 88.0% |");
    expect(report.endsWith("\n")).toBe(true);
  });

  it("shows each set apart, with the model that actually read it", () => {
    expect(compact).toContain(
      "| Set | Model | Read by | Documents | Field accuracy | Documents fully correct | Flagged | Median latency |",
    );
    expect(compact).toContain(
      "| synthetic | llama3.2 | llama3.2 | 30 | 91.7% | 50.0% | 40.0% | 40.0 s |",
    );
    expect(compact).toContain(
      "| scanned | llama3.2 | none | 5 | 80.0% | 20.0% | 100.0% | 300.0 s |",
    );
  });

  it("names the vision model and its prompt when scans were measured", () => {
    const withScans = renderReport([summary("llama3.2", 0.9)], {
      date: "2026-10-31",
      promptVersion: "text-v2",
      vision: { model: "qwen2.5vl:3b", promptVersion: "vision-v1" },
      sets: [
        { name: "synthetic", documents: 5 },
        { name: "scanned", documents: 5 },
      ],
    });

    expect(withScans).toContain(
      "Prompt `text-v2`. Scans read by `qwen2.5vl:3b` with prompt `vision-v1`. Sets: synthetic (5 documents), scanned (5 documents).",
    );
  });

  it("is already formatted the way Prettier would write it", async () => {
    const options = (await resolveConfig(import.meta.filename)) ?? {};

    expect(await format(report, { ...options, parser: "markdown" })).toBe(report);
  });
});
